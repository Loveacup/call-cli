"""Run in a fresh isolated HOME with the installed Hermes Python environment."""
import json
import os
from pathlib import Path
import sys
import unittest


@unittest.skipUnless(os.environ.get('RUN_HERMES_RELEASE_TESTS') == '1', 'opt-in real Hermes routing and IPC')
class RouteTests(unittest.TestCase):
    def test_real_factory_auth_profile_scope_and_private_ipc(self):
        # Containment is asserted before importing any Hermes module.
        home = Path(os.environ['CALLCLI_TEST_HOME']).resolve()
        scratch = Path(os.environ['CALLCLI_TEST_SCRATCH']).resolve()
        self.assertTrue(home.is_relative_to(scratch))
        self.assertEqual(Path(os.environ['HOME']).resolve(),home)
        self.assertEqual(Path(os.environ['HERMES_HOME']).resolve(),home)
        self.assertEqual(os.environ['HERMES_DISABLE_LAZY_INSTALLS'],'1')
        from types import SimpleNamespace
        from unittest.mock import patch
        from fastapi import FastAPI
        from starlette.testclient import TestClient
        from hermes_cli import web_server, web_server_dashboard as dashboard
        from hermes_cli.plugin_host import PluginHost
        from test_release_workflow import fixture
        release, _, _ = fixture(home)
        self.assertEqual(release.store.path,home/'plugin-data/call-cli/tasks.sqlite3')
        self.assertFalse((home/'call-cli/tasks.sqlite3').exists())
        (home/'config.yaml').write_text(json.dumps({'plugins':{'enabled':['call-cli'],'isolation':'host'}}))
        plugin = {'name':'call-cli','source':'user','_dir':str(Path(__file__).parent/'dashboard'),
                  '_api_file':'plugin_api.py'}
        host = PluginHost(SimpleNamespace(home_path=home,_plugins={}))
        app = FastAPI()
        # Real factory, real hosted forwarder, real parent gate, real child IPC;
        # discovery is pinned to this candidate instead of scanning installed plugins.
        try:
            with patch.object(dashboard,'_hosted_plugin_for_request',return_value=(host,plugin['_dir'],plugin['_api_file'])), \
                 patch.object(web_server,'_get_dashboard_plugins',return_value=[plugin]):
                with dashboard._plugin_api_mount_lock:
                    self.assertTrue(dashboard._mount_one_plugin_api(app,plugin,{'call-cli'},set()))
                client=TestClient(app)
                path='/api/plugins/call-cli/release/prepare'
                for params in ({},{'authenticated':'true'}):
                    response=client.post(path,params=params,json={'approved':True},
                                         headers={'X-Hosted-Http-Authenticated':'true'})
                    self.assertIn(response.status_code,(401,404))
                # Synthetic token generated by Hermes on this isolated module import.
                headers={web_server._SESSION_HEADER_NAME:web_server._SESSION_TOKEN}
                import sqlite3
                from contextlib import closing
                def database_snapshot():
                    with closing(sqlite3.connect(release.store.path)) as db:
                        return list(db.iterdump())
                before_get=database_snapshot()
                with closing(sqlite3.connect(release.store.path)) as writer:
                    writer.execute('BEGIN IMMEDIATE')
                    response=client.get('/api/plugins/call-cli/release/receipt',headers=headers)
                    self.assertEqual(response.status_code,200,response.text)
                    self.assertEqual(response.json(),{'receipt':{'state':'not_prepared'}})
                    writer.rollback()
                self.assertEqual(database_snapshot(),before_get)
                prepared=client.post(path,headers=headers)
                self.assertEqual(prepared.status_code,200,prepared.text)
                self.assertEqual(prepared.json()['target']['id'],release.policy['task'])
                self.assertNotEqual(host.pid,os.getpid())
                self.assertEqual(client.post(path).status_code,401)
                self.assertEqual(client.post(path+'?profile=missing',headers=headers).status_code,404)
                forged=client.post('/api/plugins/call-cli/release',headers=headers,
                                   json={'nonce':'approved','operation':'release-only','owner':'forged'})
                self.assertEqual(forged.status_code,409)
                self.assertIsNone(release.receipt())
                before_get=database_snapshot()
                with closing(sqlite3.connect(release.store.path)) as writer:
                    writer.execute('BEGIN IMMEDIATE')
                    response=client.get('/api/plugins/call-cli/release/receipt',headers=headers)
                    self.assertEqual(response.json(),{'receipt':None})
                    writer.rollback()
                self.assertEqual(database_snapshot(),before_get)
                self.assertEqual(release.store.get(release.policy['task'])['state'],'completed')
                # Complete the authenticated route with real ACPX and a synthetic
                # endpoint. No handler injection or self-minted operator principal.
                import subprocess, shlex
                agent=shlex.join([sys.executable,'-B',str(Path(__file__).parent/'fixtures/native_shared_agent.py'),
                                 str(home/'native-trace.jsonl'),'final-answer'])
                def cli(*args):
                    result=subprocess.run(['acpx','--agent',agent,'--cwd',str(home),'--format','json',*args],
                                          capture_output=True,timeout=30)
                    self.assertEqual(result.returncode,0,result.stderr.decode())
                    return json.loads(result.stdout)
                native=cli('sessions','new','--name',release.policy['session'])
                try:
                    release.policy.update(record=native['acpxRecordId'],acp=native['acpxSessionId'],agent=agent)
                    release.store.update(release.policy['task'],acpx_record_id=native['acpxRecordId'],agent=agent)
                    policy_path=home/'plugin-data/call-cli/release-policy.json'
                    policy_path.write_text(json.dumps(release.policy))
                    loader="const{loadRuntime}=require('./shared-prompt.cjs');(async()=>{const p=JSON.parse(process.argv[1]);const s=await loadRuntime('0.22.0');const r=s.createSharedAcpRuntime({cwd:p.cwd,permissionMode:'approve-reads'});const h={backend:'acpx-shared',acpxRecordId:p.record,sessionKey:p.session,runtimeSessionName:p.record,cwd:p.cwd};const t=r.startTurn({handle:h,text:'SYNTHETIC ONLY',requestId:p.task+':4',mode:'prompt'});for await(const e of t.events){};const x=await t.result;if(x.status!=='completed')throw Error('TURN_FAILED');await r.shutdown();})().catch(()=>process.exitCode=1);"
                    result=subprocess.run(['node','-e',loader,json.dumps(release.policy)],capture_output=True,timeout=35)
                    self.assertEqual(result.returncode,0,result.stderr.decode())
                    prepared=client.post(path,headers=headers)
                    self.assertEqual(prepared.status_code,200,prepared.text)
                    response=client.post('/api/plugins/call-cli/release',headers=headers,
                                         json={'nonce':prepared.json()['nonce'],'operation':'release-only'})
                    self.assertEqual(response.status_code,200,response.text)
                    self.assertEqual(response.json()['state'],'released',response.text)
                    self.assertEqual(release.store.get(release.policy['task'])['origin'],release.policy['owner'])
                    self.assertEqual(cli('status','-s',release.policy['session'])['status'],'no-session')
                    self.assertEqual(client.post(path,headers=headers).json()['receipt']['state'],'released')
                finally:
                    if cli('status','-s',release.policy['session'])['status']!='no-session':
                        cli('sessions','close',release.policy['session'])
                # Direct IPC strictness is separately tested without falsely treating it
                # as HTTP authentication. Header/body/query cannot stamp request state.
                args=('call-cli',plugin['_dir'],plugin['_api_file'],'POST','/release/prepare',
                      'authenticated=true',[('X-Hosted-Http-Authenticated','true')],b'{}')
                for marker in (False,None,'true',1):
                    self.assertEqual(host.asgi_request(*args,authenticated=marker)['status'],401)
                self.assertEqual(host.asgi_request(*args,authenticated=True)['status'],404)
                # Reject query variants rather than skipping validation on them.
                self.assertEqual(client.post(path+'?approved=true',headers=headers).status_code,404)
        finally:
            host.shutdown()
        print('REAL_FACTORY_AUTH_PROFILE_ISOLATED_IPC_OK')


if __name__=='__main__':unittest.main()
